export const AIRPORTS: Airport[] = MAJOR_AIRPORTS.map(
  ([iata, name, city, country, continent, lat, lon, aliasStr]) => ({
    iata,
    name,
    city,
    country,
    continent,
    lat,
    lon,
    ...(aliasStr
      ? {
          aliases: aliasStr
            .split(',')
            .map(item => item.trim())
            .filter(Boolean),
        }
      : {}),
  }),
)

const byIata = new Map(AIRPORTS.map(airport => [airport.iata, airport]))

export function getAirport(iata: string) {
  return byIata.get(iata.toUpperCase())
}

export function formatAirport(airport: Airport) {
  return `${airport.city} (${airport.iata})`
}

function normalize(value: string) {
  return value
    .toLowerCase()
    .replace(/\bsaint\b/g, 'st')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function corePlace(value: string) {
  return normalize(value)
    .replace(
      /\b(city|international|airport|intl|municipal|regional|metro)\b/g,
      '',
    )
    .replace(/\s+/g, ' ')
    .trim()
}

function tokens(value: string) {
  return corePlace(value).split(' ').filter(Boolean)
}

function tokenMatch(haystack: string, needle: string) {
  const hay = tokens(haystack)
  const query = tokens(needle)
  if (hay.length === 0 || query.length === 0) return false
  const haySet = new Set(hay)
  const querySet = new Set(query)
  return (
    query.every(token => haySet.has(token)) ||
    hay.every(token => querySet.has(token))
  )
}

function searchFields(airport: Airport) {
  return [airport.city, airport.name, ...(airport.aliases ?? [])]
}

function metroKey(airport: Airport) {
  return `${corePlace(airport.city)}|${normalize(airport.country)}`
}

const metroSize = new Map<string, number>()
for (const airport of AIRPORTS) {
  const key = metroKey(airport)
  metroSize.set(key, (metroSize.get(key) ?? 0) + 1)
}

export function searchAirports(query: string, limit = 12) {
  const raw = query.trim()
  if (!raw) return AIRPORTS.slice(0, limit)

  const needle = normalize(raw)
  const needleCore = corePlace(raw)

  const scored = AIRPORTS.map((airport, index) => {
    const iata = airport.iata.toLowerCase()
    const city = normalize(airport.city)
    const cityCore = corePlace(airport.city)
    const aliasCores = (airport.aliases ?? []).map(alias => corePlace(alias))
    const aliasNorms = (airport.aliases ?? []).map(alias => normalize(alias))
    const fields = searchFields(airport)
    let score = 0

    if (iata === needle) score = 100
    else if (iata.startsWith(needle) && needle.length >= 3) score = 90
    else if (needleCore && cityCore === needleCore) score = 86
    else if (
      needleCore &&
      (aliasCores.includes(needleCore) || aliasNorms.includes(needle))
    ) {
      score = 84
    } else if (iata.startsWith(needle)) score = 82
    else if (
      city.startsWith(needle) ||
      (needleCore && cityCore.startsWith(needleCore))
    ) {
      score = 80
    } else if (fields.some(field => tokenMatch(field, raw))) score = 74
    else if (
      needle.length >= 3 &&
      fields.some(field => normalize(field).includes(needle))
    ) {
      score = 60
    } else if (needle.length >= 3 && normalize(airport.name).includes(needle)) {
      score = 40
    } else if (
      needle.length >= 3 &&
      normalize(airport.country).includes(needle)
    ) {
      score = 20
    }

    return { airport, score, index }
  })
    .filter(row => row.score > 0)
    .sort((a, b) => {
      if (b.score !== a.score) return b.score - a.score
      const metro =
        (metroSize.get(metroKey(b.airport)) ?? 0) -
        (metroSize.get(metroKey(a.airport)) ?? 0)
      if (metro !== 0) return metro
      return a.index - b.index
    })

  return scored.slice(0, limit).map(row => row.airport)
}

function haversineKm(a: Airport, b: Airport) {
  const toRad = (deg: number) => (deg * Math.PI) / 180
  const dLat = toRad(b.lat - a.lat)
  const dLon = toRad(b.lon - a.lon)
  const lat1 = toRad(a.lat)
  const lat2 = toRad(b.lat)
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2
  return 2 * 6371 * Math.asin(Math.min(1, Math.sqrt(h)))
}

export function nearbyAirports(
  iataCodes: string[],
  radiusKm = NEARBY_RADIUS_KM,
) {
  const origins = iataCodes
    .map(code => getAirport(code))
    .filter((airport): airport is Airport => Boolean(airport))
  if (origins.length === 0) return []

  const seen = new Set(origins.map(airport => airport.iata))
  const nearby: Airport[] = []

  for (const candidate of AIRPORTS) {
    if (seen.has(candidate.iata)) continue
    const distance = Math.min(
      ...origins.map(origin => haversineKm(origin, candidate)),
    )
    if (distance <= radiusKm) {
      nearby.push(candidate)
      seen.add(candidate.iata)
    }
  }

  return nearby
}

export function describeAirports(iataCodes: string[]) {
  return iataCodes
    .map(code => {
      const airport = getAirport(code)
      return airport ? `${airport.iata} (${airport.city})` : code
    })
    .join(', ')
}

export function isContinent(value: string): value is Continent {
  return (CONTINENTS as readonly string[]).includes(value)
}
